import { expect } from 'vitest'

/** 验证放大只改变布局，保留输入、画布与实际屏幕上的回放限制。 */
export async function verifyStoryStage(page, composer) {
  const expandStage = page.getByRole('button', { name: '全窗口舞台' })
  const originalCanvas = await page.locator('.home-canvas canvas').first().elementHandle()
  await composer.fill('留在编辑器里的草稿')
  await expandStage.click()
  expect(await composer.inputValue()).toBe('留在编辑器里的草稿')
  expect(await page.locator('.home-sidebar').isVisible()).toBe(false)
  await page.screenshot({ path: '/tmp/sakiko-story-composer.png', scale: 'css' })
  const storyRail = page.getByRole('navigation', { name: '剧情舞台工具栏' })
  const openRail = storyRail.getByRole('button', { name: '展开工具栏' })
  const closeRail = storyRail.getByRole('button', { name: '收起工具栏' })
  const restoreStage = storyRail.getByRole('button', { name: '退出', exact: true })
  const log = storyRail.getByRole('button', { name: '剧情记录' })
  expect(await storyRail.getByRole('button').count()).toBe(1)
  expect(await openRail.getAttribute('aria-expanded')).toBe('false')
  const closedBounds = await openRail.boundingBox()
  await openRail.click()
  expect(await closeRail.getAttribute('aria-expanded')).toBe('true')
  expect(await restoreStage.isVisible()).toBe(true)
  expect(await closeRail.boundingBox()).toEqual(closedBounds)
  const strip = storyRail.locator('.story-strip')
  expect(await strip.boundingBox()).toMatchObject({
    x: closedBounds.x,
    y: closedBounds.y + closedBounds.height,
    width: closedBounds.width
  })
  await storyRail.screenshot({ path: '/tmp/sakiko-story-toolbar.png', scale: 'css' })
  const automatic = storyRail.getByRole('button', { name: '自动', exact: true })
  await page.getByRole('button', { name: '收起回复' }).click()
  await log.click()
  const storyLog = page.getByRole('dialog', { name: '剧情记录' })
  await storyLog.getByText('今天也辛苦了，先休息一会儿吧。', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await expandStage.waitFor()
  expect(await composer.inputValue()).toBe('留在编辑器里的草稿')
  expect(
    await originalCanvas.evaluate((node) => node === document.querySelector('.home-canvas canvas'))
  ).toBe(true)
  await composer.fill('')
  await expandStage.click()
  expect(await storyRail.getByRole('button').count()).toBe(1)
  await openRail.click()
  const replayStory = storyRail.getByRole('button', { name: '回放', exact: true })
  // 字幕出现时演出可能仍在播放，回放入口要等该轮真正结束。
  await expect.poll(() => replayStory.isEnabled(), { timeout: 15000 }).toBe(true)
  expect(await automatic.isEnabled()).toBe(true)
  expect(await automatic.getAttribute('aria-pressed')).toBe('false')
  await replayStory.click()
  expect(await automatic.getAttribute('aria-pressed')).toBe('false')
  const stageTools = storyRail.getByRole('button', { name: '舞台', exact: true })
  await stageTools.click()
  expect(await page.getByRole('button', { name: '切换服装' }).isDisabled()).toBe(true)
  expect(await page.getByRole('button', { name: '切换背景' }).isDisabled()).toBe(true)
  await closeRail.click()
  expect(await storyRail.getByRole('button').count()).toBe(1)
  expect(await page.getByRole('group', { name: '舞台工具' }).isVisible()).toBe(false)
  await openRail.press('Enter')
  expect(await stageTools.getAttribute('aria-expanded')).toBe('false')
  expect(await storyRail.getByRole('button', { name: '停止', exact: true }).isVisible()).toBe(true)
  await restoreStage.click()
  await expandStage.waitFor()
  expect(await originalCanvas.evaluate((node) => node.isConnected)).toBe(true)
}

/** 用有声音的多句回复覆盖两种布局切换及记录页试听抢占。 */
export async function verifyStoryAudio(page, firstLine) {
  const button = (name) => page.getByRole('button', { name, exact: true })
  const audioCount = () => page.evaluate(() => window.historyAudio.length)
  const before = await audioCount()
  await button('展开聊天记录').click()
  await button('回放本轮回复').click()
  await button('收起聊天记录').click()
  await expect.poll(audioCount).toBe(before + 1)
  await button('全窗口舞台').click()
  await page.locator('.story-words').waitFor()
  expect(await page.locator('.story-words').textContent()).toBe(firstLine)
  await page.keyboard.press('Escape')
  expect(await audioCount()).toBe(before + 1)
  expect(await page.evaluate(() => window.historyAudio.at(-1).paused)).toBe(false)
  await button('全窗口舞台').click()
  await button('展开工具栏').click()
  await button('自动').click()
  await button('剧情记录').click()
  const log = page.getByRole('dialog', { name: '剧情记录' })
  expect(await page.evaluate(() => window.historyAudio.at(-1).paused)).toBe(true)
  expect(await log.getByText('先核对线索').count()).toBe(0)
  const listen = log.getByRole('button', { name: '重播语音' })
  expect(await listen.count()).toBe(2)
  await listen.first().click()
  await expect.poll(audioCount).toBe(before + 2)
  await log.getByRole('button', { name: '停止试听' }).click()
  await page.screenshot({ path: '/tmp/sakiko-story-history.png', scale: 'css' })
  await button('关闭剧情记录').click()
  await expect.poll(audioCount).toBe(before + 3)
  expect(await page.locator('.story-words').textContent()).toBe(firstLine)
  // 同一轮已在回放时，从用户消息选择它仍应从头演出。
  await button('剧情记录').click()
  const turnButton = log.locator('[data-kind="user"]').getByRole('button', { name: '回放本轮回复' })
  await turnButton.click()
  await log.waitFor({ state: 'detached' })
  await expect.poll(audioCount).toBe(before + 4)
  expect(await page.locator('.story-words').textContent()).toBe(firstLine)
  // 让第一句停在句尾，再区分点击工具、拖动角色和轻点角色。
  const next = button('下一句')
  await next.waitFor()
  await button('收起工具栏').click()
  const canvas = await page.locator('.home-canvas').boundingBox()
  const x = canvas.x + canvas.width / 2
  const y = canvas.y + canvas.height / 3
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 32, y, { steps: 4 })
  await page.mouse.move(x, y, { steps: 4 })
  await page.mouse.up()
  expect(await next.isVisible()).toBe(true)
  expect(await audioCount()).toBe(before + 4)
  await page.mouse.click(x, y)
  await expect.poll(audioCount).toBe(before + 5)
  expect(await page.locator('.story-words').textContent()).not.toBe(firstLine)
  await page.keyboard.press('Escape')
  await button('停止本轮回放').click()
}
