import { expect } from 'vitest'

/** @param {object} page Electron 页面。 @param {object} backend 隔离的后端。 @param {string} chatId 专用会话副本。 */
export async function verifyHistoryActions(page, backend, chatId) {
  await page.getByRole('button', { name: '设置', exact: true }).click()
  const settings = page.getByRole('dialog', { name: '设置' })
  await settings.getByRole('button', { name: '对话导入 / 导出', exact: true }).click()
  await settings.getByRole('button', { name: '导出所选 1 个对话…' }).waitFor()
  await settings.getByRole('tab', { name: '导入对话', exact: true }).click()
  await settings.getByRole('button', { name: '导入对话…' }).waitFor()
  await settings.getByRole('button', { name: '关闭设置', exact: true }).click()
  await page.getByRole('button', { name: '展开聊天记录' }).click()
  const history = page.locator('.history-panel')
  const draft = page.getByRole('textbox', { name: '消息', exact: true })
  await draft.fill('尚未发送的草稿')
  const userMenu = history.locator('.history-user [aria-haspopup=menu]').last()
  await userMenu.click()
  await page.getByRole('menuitem', { name: '编辑消息', exact: true }).click()
  await history.getByRole('textbox', { name: '编辑消息' }).fill('原地修改')
  await history.getByRole('button', { name: '保存修改' }).click()
  await history.getByText('原地修改', { exact: true }).waitFor()
  expect(await history.locator('.history-assistant').count()).toBe(3)
  await history.locator('.history-assistant [aria-haspopup=menu]').first().click()
  expect(await page.getByRole('menuitem', { name: '编辑消息' }).count()).toBe(0)
  await page.getByRole('menuitem', { name: '重新生成这句音频' }).click()
  await userMenu.click()
  await page.getByRole('menuitem', { name: '编辑并重发' }).click()
  await history.getByRole('textbox', { name: '编辑消息' }).fill('重新提交')
  await history.getByRole('button', { name: '保存并重新生成' }).click()
  await history
    .locator('.history-user .history-bubble')
    .getByText('重新提交', { exact: true })
    .waitFor()
  const snapshot = () => backend.conversations.getSnapshot(chatId)
  await expect
    .poll(async () => (await snapshot()).admission.canGenerate, { timeout: 20000 })
    .toBe(true)
  expect(await draft.inputValue()).toBe('尚未发送的草稿')
  await expect
    .poll(async () => (await snapshot()).chat.turns[0].messages[0].content.text)
    .toBe('重新提交')
  const previous = (await snapshot()).chat.turns[0].id
  await history.getByRole('button', { name: '重新生成回复', exact: true }).click()
  await history.getByRole('button', { name: '重新生成', exact: true }).click()
  await expect.poll(async () => (await snapshot()).chat.turns[0].id).not.toBe(previous)
  await expect
    .poll(async () => (await snapshot()).admission.canGenerate, { timeout: 20000 })
    .toBe(true)
  await draft.fill('第二轮')
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect.poll(async () => (await snapshot()).chat.turns.length).toBe(2)
  await expect
    .poll(async () => (await snapshot()).admission.canGenerate, { timeout: 20000 })
    .toBe(true)
  const first = history.locator('.history-turn').first()
  const before = new Set((await backend.conversations.listChats()).map((item) => item.id))
  await first.getByRole('button', { name: '本轮操作' }).click()
  await page.getByRole('menuitem', { name: '从本轮结束处分叉' }).click()
  await history.getByRole('button', { name: '返回原对话' }).click()
  const copies = await backend.conversations.listChats()
  const branch = copies.find((item) => !before.has(item.id))
  expect((await backend.conversations.getSnapshot(branch.id)).chat.turns).toHaveLength(1)
  await backend.conversations.deleteChat(branch.id)
  await first.getByRole('button', { name: '本轮操作' }).click()
  await page.getByRole('menuitem', { name: '回溯到本轮结束' }).click()
  await history.getByRole('button', { name: '移除后续 1 轮' }).click()
  await expect.poll(async () => (await snapshot()).chat.turns.length).toBe(1)
  await page.getByRole('button', { name: '收起聊天记录' }).click()
}
