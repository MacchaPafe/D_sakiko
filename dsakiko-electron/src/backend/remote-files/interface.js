/** @typedef {import('../../shared/contracts/common.js').AssetRef} AssetRef */

/**
 * 仅供当前连接的消息组装使用；与产生它的连接作用域绑定，不保存到 Chat。
 * 文件有效期、远端删除标识和所属资源的对应关系由模块内部记录，不由调用方推导。
 * @typedef {object} RemoteFileRef
 * @property {'file-id' | 'file-uri'} kind 消息协议要求的引用形式。
 * @property {string} value 文件标识或 URI；URI 不一定是厂商删除接口使用的标识。
 */

/**
 * 远端文件模块：确保本地资源具有可用的厂商文件引用，管理上传复用、失效与远端清理。
 * 实例在装配时绑定服务地址、凭据作用域、文件用途和协议；与本次模型请求使用同一连接快照。
 * 配置变化产生新的连接绑定，不修改运行中实例；缓存按实际作用域区分，不能只按 connectionId 区分。
 * 文件名、类型和内容通过 MediaAssets 读取；上传期间持有临时资源引用，消息请求也由调用方持有至结束。
 * 远端引用及其清理记录可存于内部缓存，不是聊天附件的唯一来源；Chat 始终保存本地 AssetRef。
 *
 * 需要：本地资源、已装配的连接能力、资源存活信息，以及明确的失效或删除指令。
 * 不需要：Chat/Turn 对象、输入框状态、全局当前模型、完整角色、消息保存方式或重试整个生成流程的决定。
 * file-api 与 inline 的选择属于连接配置和请求组装；inline 不经过本模块，不把 base64 伪装成远端引用。
 * 内部适配厂商上传、处理状态查询与删除协议；本接口不假设各厂商只差一个 URL。
 * 这是审查用接口，方法均未实现。
 */
export class RemoteFiles {
  /**
   * 复用当前作用域内的有效引用，或上传本地资源并等待厂商完成必要处理；预上传与正式发送共用此方法。
   * 按资源和实际连接作用域合并并发上传；不能返回正在删除、已失效或已知即将过期的引用。
   * 取消只结束本次调用，其他等待者继续；无人等待时可尝试中断，迟到产生的远端文件仍需记录并清理。
   * Promise 完成表示引用已可用于请求；缓存命中不保证厂商之后一定接受，明确拒绝时使用 invalidate。
   * @param {AssetRef} asset 已导入且可读取的本地资源。
   * @param {AbortSignal} [signal] 取消本次准备，不取消其他调用者的使用。
   * @returns {Promise<RemoteFileRef>} 当前连接可使用的引用；上传、处理失败或不支持的资源拒绝 Promise。
   */
  async ensureUploaded(asset, signal) {}

  /**
   * 将厂商明确拒绝的旧引用标记为不可复用；只有知道文件失效的调用方才发出此指令。
   * 只影响指定引用，不能使同一资源并发取得的新引用失效；不立即上传或删除远端文件。
   * 限流、鉴权或其他请求错误不应转换成引用失效，整个生成请求是否重试由 Agent 决定。
   * @param {RemoteFileRef} reference 请求中实际使用、属于当前作用域的旧引用。
   * @returns {Promise<void>} 后续准备不再复用此引用；未知或其他作用域的引用拒绝。
   */
  async invalidate(reference) {}

  /**
   * 对指定的已上传文件立即发起厂商删除请求，不等待自动回收，也不以仍有本地引用为由延后。
   * 先将此引用标记为不可再交付，再请求删除；旧引用的删除不能影响同一资源的新上传结果。
   * 可使已经使用此引用的模型请求失败；是否先取消或等待这些请求由调用方决定，模块不控制 Chat。
   * 成功只删除指定远端副本，保留本地资源；之后再次 ensureUploaded 仍可产生新的远端文件。
   * 删除失败或结果不确定时拒绝 Promise，保留待清理记录且不重新启用旧引用；进入待清理队列不代表成功。
   * @param {RemoteFileRef} reference 本模块已登记、属于当前作用域的文件引用，不接受任意账号文件标识。
   * @returns {Promise<void>} 厂商确认删除或明确确认文件已不存在；已确认删除的同一引用重复调用无副作用。
   */
  async delete(reference) {}

  /**
   * 回收本模块上传且已无人使用的远端文件及缓存记录，不扫描删除账号内其他文件。
   * 通过受限资源生命周期能力检查草稿、存档及任务引用，避开正在上传或使用的资源。
   * 待删除引用先退出可复用集合；显式 delete 已登记的清理意图不受自动回收的引用条件限制。
   * 删除失败保留待清理记录并报告内部诊断；不得把失败的远端删除当作已完成而丢失记录。
   * @returns {Promise<void>} 本轮清理检查结束，不保证所有待清理远端文件均已删除。
   */
  async collectUnused() {}
}
